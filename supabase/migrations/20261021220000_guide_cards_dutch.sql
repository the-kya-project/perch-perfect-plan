-- Parrots 101 in Dutch: guide content is DATA (guide_cards rows), so Dutch
-- lives beside the English in *_nl columns — one row per card, which matches
-- how the app reads the table (select * ordered by category/title; the guide
-- screen picks the _nl field per language and falls back to English per field).
--
-- Not localized: slug, category and search_keywords (mapping/search inputs,
-- never shown), reviewed_by/reviewed_at. The guide's search runs over the
-- localized display fields PLUS the English search_keywords, so both languages
-- keep working search.
--
-- The Dutch below translates the CURRENT English rows (the 20260615135444 seed
-- plus the 20261021190000 "no scan in visible copy" wording), hand-written with
-- the locked glossary (health scan → gezondheidscheck, care plan →
-- verzorgingsplan, informal "je") and the register of nl.jsonc. Temperatures
-- are given in Celsius with the original Fahrenheit in parentheses.
--
-- Idempotent: add column if not exists; the UPDATE re-applies the same values
-- on a re-run. A card added later without Dutch simply falls back to English.

alter table public.guide_cards
  add column if not exists title_nl text,
  add column if not exists quick_answer_nl text,
  add column if not exists what_to_check_nl text,
  add column if not exists what_to_do_nl text,
  add column if not exists when_to_call_vet_nl text;

comment on column public.guide_cards.title_nl is 'Dutch title; null falls back to title.';
comment on column public.guide_cards.quick_answer_nl is 'Dutch quick_answer; null falls back to quick_answer.';
comment on column public.guide_cards.what_to_check_nl is 'Dutch what_to_check; null falls back to what_to_check.';
comment on column public.guide_cards.what_to_do_nl is 'Dutch what_to_do; null falls back to what_to_do.';
comment on column public.guide_cards.when_to_call_vet_nl is 'Dutch when_to_call_vet; null falls back to when_to_call_vet.';

